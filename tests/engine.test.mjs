import test from 'node:test';
import assert from 'node:assert/strict';
import {normalize, newSession, respond} from '../js/engine.mjs';
const talk = text => respond(text,newSession());
test('normalizes input',()=>assert.equal(normalize('  HELLO,    World!!  '),'hello world'));
test('empty input is rejected',()=>assert.equal(talk('  ').intent,'empty'));
test('greeting',()=>assert.equal(talk('Hello there').intent,'greeting'));
test('whole words do not match partial hi',()=>assert.equal(talk('this is random').intent,'fallback'));
test('BFS keyword',()=>assert.equal(talk('What is BFS?').intent,'bfs'));
test('DFS phrase',()=>assert.equal(talk('depth first search').intent,'dfs'));
test('A star recognized',()=>assert.equal(talk('A* search').intent,'astar'));
test('minimax recognized',()=>assert.equal(talk('Tic tac toe').intent,'minimax'));
test('github intent',()=>assert.equal(talk('How do I push to GitHub?').intent,'github'));
test('programming intent',()=>assert.equal(talk('JavaScript advice').intent,'python'));
test('internship intent',()=>assert.equal(talk('internship tips').intent,'internship'));
test('specific topic outranks greeting',()=>assert.equal(talk('hey explain BFS').intent,'bfs'));
test('name capture and recall',()=>{const s=newSession();respond('My name is Alvy Rahman',s);assert.match(respond('what is my name?',s).reply,/Alvy Rahman/)});
test('recall before name',()=>assert.match(talk("what's my name?").reply,/don't know/i));
test('contextual followup',()=>{const s=newSession();respond('What is A* search?',s);assert.match(respond('tell me more',s).reply,/optimality/i)});
test('unknown fallback',()=>assert.equal(talk('quantum mechanical jellybeans').intent,'fallback'));
test('goodbye flag',()=>{const s=newSession();assert.equal(respond('bye',s).intent,'goodbye');assert.equal(s.closed,true)});
test('session state resets',()=>{const s=newSession();respond('My name is Alex',s);assert.equal(newSession().name,null)});
